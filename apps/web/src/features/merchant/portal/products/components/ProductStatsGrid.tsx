'use client';

import React from 'react';
import { Package, Eye, TrendingUp, AlertTriangle } from 'lucide-react';
import { ProductStats } from '../types';

interface ProductStatsGridProps {
  stats: ProductStats;
}

export function ProductStatsGrid({ stats }: ProductStatsGridProps) {
  const statItems = [
    {
      label: 'Store Products',
      value: stats.storeProducts,
      subtitle: 'Products currently in your store',
      icon: <Package className="h-4 w-4 text-emerald-400" />,
      accentBg: 'bg-emerald-500/10 border-emerald-500/20 text-emerald-400',
    },
    {
      label: 'Published',
      value: stats.published,
      subtitle: 'Visible to your customers',
      icon: <Eye className="h-4 w-4 text-emerald-400" />,
      accentBg: 'bg-emerald-500/10 border-emerald-500/20 text-emerald-400',
    },
    {
      label: 'Total Orders',
      value: stats.totalOrders,
      subtitle: 'Orders generated by these products',
      icon: <TrendingUp className="h-4 w-4 text-emerald-400" />,
      accentBg: 'bg-emerald-500/10 border-emerald-500/20 text-emerald-400',
    },
    {
      label: 'Low Stock',
      value: stats.lowStock,
      subtitle: 'Products that need attention',
      icon: <AlertTriangle className="h-4 w-4 text-amber-400" />,
      accentBg: stats.lowStock > 0 ? 'bg-amber-500/10 border-amber-500/20 text-amber-400' : 'bg-emerald-500/10 border-emerald-500/20 text-emerald-400',
      valueColor: stats.lowStock > 0 ? 'text-amber-400' : 'text-slate-100',
    },
  ];

  return (
    <div className="grid grid-cols-2 lg:grid-cols-4 gap-2.5 sm:gap-4">
      {statItems.map((item) => (
        <div
          key={item.label}
          className="rounded-xl border border-slate-800 bg-slate-900/90 p-3 sm:p-5 shadow-sm transition-all hover:border-slate-700/80 flex flex-col justify-between"
        >
          <div className="flex items-center justify-between gap-1">
            <span className="text-[11px] sm:text-xs font-semibold tracking-wide text-slate-400 truncate">
              {item.label}
            </span>
            <div className={`h-7 w-7 sm:h-8 sm:w-8 rounded-lg border flex items-center justify-center shrink-0 ${item.accentBg}`}>
              {item.icon}
            </div>
          </div>
          <div className="mt-2 sm:mt-3">
            <span className={`text-xl sm:text-3xl font-extrabold tracking-tight ${item.valueColor || 'text-slate-100'}`}>
              {item.value}
            </span>
            <p className="text-[10px] sm:text-xs text-slate-400 mt-0.5 sm:mt-1 line-clamp-1 sm:line-clamp-none">
              {item.subtitle}
            </p>
          </div>
        </div>
      ))}
    </div>
  );
}
